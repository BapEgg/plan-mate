package com.planmate.trip.domain;

public enum TripInterest {
    /**
     * 음식, 맛집, 현지 식문화에 관심이 있다. 후보 검색에서는 MEAL 가중치를 높인다.
     */
    FOOD,

    /**
     * 대표 관광지와 필수 방문 명소에 관심이 있다. 후보 검색에서는 CORE_VISIT 가중치를 높인다.
     */
    SIGHTSEEING,

    /**
     * 카페 방문과 디저트 경험에 관심이 있다.
     */
    CAFE,

    /**
     * 역사, 전통, 문화 체험에 관심이 있다.
     */
    CULTURE,

    /**
     * 자연 경관과 야외 명소에 관심이 있다.
     */
    NATURE,

    /**
     * 쇼핑 장소와 상권 방문에 관심이 있다.
     */
    SHOPPING,

    /**
     * 사진 찍기 좋은 장소에 관심이 있다.
     */
    PHOTO,

    /**
     * 야경 명소와 저녁 시간대 방문지에 관심이 있다.
     */
    NIGHT_VIEW,

    /**
     * 체험형 활동과 액티비티에 관심이 있다.
     */
    ACTIVITY,

    /**
     * 휴식, 산책, 여유로운 장소에 관심이 있다.
     */
    REST,

    /**
     * 미술관, 전시, 예술 공간에 관심이 있다.
     */
    ART,

    /**
     * 테마파크나 놀이시설에 관심이 있다.
     */
    THEME_PARK,

    /**
     * 현지인 감성의 로컬 장소에 관심이 있다.
     */
    LOCAL
}
